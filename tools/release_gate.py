def шапка(тело: bytes) -> dict | None:
    """YAML-шапка .md в словарь. None — шапки нет, не закрыта или не разобралась."""
    t = текст(тело)
    if t is None or not t.startswith("---"):
        return None
    конец = t.find(chr(10) + "---", 3)
    if конец < 0 or yaml is None:
        return None
    try:
        d = yaml.safe_load(t[3:конец])
    except Exception:
        return None
    return d if isinstance(d, dict) else None


def _значимые(d: dict) -> set[str]:
    s = " ".join(str(d.get(k, "")) for k in ("description", "scope"))
    return {w.lower().strip(".-") for w in G12_СЛОВО.findall(s)} - G12_СТОП


