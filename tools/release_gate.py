def g15_концы_строк(о: Отчёт, м: Мишень) -> None:
    """Концы строк внутри ассета — только LF.

    ЧЕМ ОПЛАЧЕНО. 10.09.2026 перезалив 8.4.7-L, собранный с CRLF, сломал загрузку
    редакции Lite на хосте Qwen: \\r попал в хвост url в индексе, и хост пошёл
    за адресом с невидимым лишним байтом.

    ПОЧЕМУ ОТДЕЛЬНОЙ ПРОВЕРКОЙ, А НЕ ЧАСТЬЮ G06. G06 сверяет архив с источником
    ПО ТЕКСТУ с нормализацией переводов строк — она обязана так делать (в git блобы
    CRLF, сборка кладёт LF, побайтно краснело 44 файла из 47 при нулевом расхождении),
    и ровно поэтому она к этому дефекту слепа ПО ПОСТРОЕНИЮ: смешанные концы строк
    для неё совпадение. Сторожить должен тот, кто смотрит на байты.

    ИСКЛЮЧЕНИЕ. .bat/.cmd/.ps1 обязаны сохранять CRLF: cmd.exe читает их кусками,
    ища CR, и с одним LF раздел приходится на середину многобайтного UTF-8. Список
    совпадает с `.gitattributes` и с CRLF_REQUIRED в pack_release.py.
    """
    p = о.новая("G15", "концы строк внутри ассета — LF")
    for ассет in list(м.редакции.values()) + м.плагины:
        for имя, тело in записи_архива(ассет).items():
            if имя.lower().endswith(CRLF_НУЖЕН):
                continue
            if текст(тело) is None:      # бинарь — не наше дело
                continue
            p.осмотр()
            if b"\r" in тело:
                crlf = тело.count(b"\r\n")
                одиночных = тело.replace(b"\r\n", b"").count(b"\r")
                части = []
                if crlf:
                    части.append(f"CRLF {crlf}")
                if одиночных:
                    части.append(f"одиночных CR {одиночных}")
                p.провал(f"{ассет.name}: {имя} — {', '.join(части)}. "
                         "Сборка положила файл с диска как есть; на Windows рабочее "
                         "дерево лежит с CRLF")


