#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
verify_live_facts.py — приёмка фактов текущего цикла live specs по телам поставки.

ЗАЧЕМ. Факт живёт не в одном файле: цена, id модели, имя вендора и правило G-кода
размазаны по пяти телам (C for-chat, C plugin, H, N, L) и по двум слоям (BASE и live).
Правка, доехавшая до одного тела, выглядит сделанной. Этот заслон спрашивает иначе:
назван ли факт в КАЖДОМ теле, где он обязан быть, и не осталось ли ГДЕ-НИБУДЬ
отменённого значения.

Вызов:
    python tools/verify_live_facts.py                     # по рабочему дереву
    python tools/verify_live_facts.py --корень <каталог>  # по копии (мутации)
    python tools/verify_live_facts.py --пара              # парный прогон + мутация

Устройство, важное для доверия к нему:
  · обход только os.walk — glob("**/…") не заходит в каталоги с точки, и поставка
    plugin/.claude/ пропадала бы молча;
  · версия выбирается кортежем чисел, не строкой: на 8.4.10 строковая сортировка
    ушла бы проверять 8.4.6;
  · у каждой проверки печатается число ОСМОТРЕННЫХ объектов рядом с числом провалов;
    ноль осмотренных — это ПРОВАЛ, а не тишина;
  · любой провал роняет код возврата в 2. Строчка в консоли ошибкой не считается.

Таблица фактов — срез live specs v8.7.4 от 2026-09-10. При следующем цикле правится
она, а не устройство: «где обязан быть» задаётся списком тел.
"""
from __future__ import annotations

import io
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ТЕКСТ = (".md", ".txt", ".json", ".yaml", ".yml")

# Файлы, где отменённое значение — законное описание прошлого, а не утверждение.
ИСТОРИЯ = ("CHANGELOG", "RELEASE_NOTES", "HISTORY")


def тела(корень):
    """Пять тел поставки текущего поколения. Версия — кортежем чисел, не строкой."""
    ed = os.path.join(корень, "editions")
    версии = {}
    if not os.path.isdir(ed):
        return [], None
    for имя in os.listdir(ed):
        m = re.match(r"^(\d+(?:\.\d+)*)-([CHNL])$", имя)
        if m and os.path.isdir(os.path.join(ed, имя)):
            версии.setdefault(tuple(int(x) for x in m.group(1).split(".")), set()).add(m.group(2))
    if not версии:
        return [], None
    v = max(версии)
    строка = ".".join(str(x) for x in v)
    раскладка = [
        ("C for-chat", os.path.join(ed, "%s-C" % строка, "for-chat")),
        ("C plugin", os.path.join(ed, "%s-C" % строка, "plugin")),
        ("H", os.path.join(ed, "%s-H" % строка, "files")),
        ("N", os.path.join(ed, "%s-N" % строка, "files")),
        ("L", os.path.join(ed, "%s-L" % строка, "boot")),
    ]
    return [(к, п) for к, п in раскладка if os.path.isdir(п)], строка


def собрать(тела_список):
    """{ключ тела: [(путь, текст)]} — обход os.walk, каталоги с точки не теряются."""
    свод = {}
    for ключ, корень in тела_список:
        файлы = []
        for каталог, _, имена in os.walk(корень):
            for имя in имена:
                if not имя.endswith(ТЕКСТ):
                    continue
                п = os.path.join(каталог, имя)
                try:
                    файлы.append((п, io.open(п, encoding="utf-8").read()))
                except (UnicodeDecodeError, OSError):
                    continue
        свод[ключ] = файлы
    return свод


ВСЕ = ("C for-chat", "C plugin", "H", "N", "L")
БЕЗ_L = ("C for-chat", "C plugin", "H", "N")

# Строки, где прежнее написание законно: распознавание хоста (его нельзя заменять,
# только дополнять) и явное указание прежнего имени вендора.
ЗАКОННО_ПРЕЖНЕЕ = r"SYNONYMS|self==|trigger:|бывш\. xAI|аспознавание хоста"

# (код, что за факт, regex «обязан быть», тела, regex «не должно остаться» | None
#  [, regex-исключение: строки, где прежнее значение законно])
ФАКТЫ = [
    ("F1", "GPT-6 Astra как факт (A8)",
     r"gpt-6-astra", ВСЕ, None),
    ("F2", "Astra: порог 272K с кэшем и /v1/responses",
     r"272K", БЕЗ_L, None),
    ("F3", "Вендор SpaceXAI (Б2)",
     r"SpaceXAI", ВСЕ, r"\bxAI\b", ЗАКОННО_ПРЕЖНЕЕ),
    ("F4", "Claude Code 2.1.263…2.1.267 (A5/A6)",
     r"maxEffortLevel", БЕЗ_L, None),
    ("F5", "Пол версии Fable 5.1 — v2.1.257 (A6)",
     r"v2\.1\.257", БЕЗ_L, None),
    ("F6", "Правило G1 по эталону 8.7.4 (ATTENTION 14c)",
     r"deprecated", ВСЕ,
     r"temp≠1\.0|temperature\s*[:=]\s*1\.0 при Deep Think|Deep Think \+ temperature ≠ 1\.0"),
    ("F7", "Sonnet 5 — подорожание отменено (ATTENTION 14b)",
     r"claude-sonnet-5", ВСЕ,
     r"\$2 \(intro\) → \$3|\$3 c 01\.09"),
    ("F8", "Gemini 3.5 Pro — пятый пропуск GA (A11)",
     r"ПЯТЫЙ пропуск|пятый пропуск|5-й пропуск", ВСЕ,
     r"ТРЕТИЙ пропуск|третий пропуск|четвёртый пропуск|3-й пропуск|4-й пропуск"),
    # L несёт по Qwen только api-строки и strict JSON, величин выхода в нём нет
    # по устройству редакции — тела L в списке нет намеренно, а не по забывчивости.
    ("F9", "Qwen3.8-Max: max output 131 072 (A2)",
     r"131[  ,]072", ("C for-chat", "C plugin", "H", "N"), None),
    ("F10", "GLM-5.3-Flash после промо (A1)",
     r"\$0\.15", БЕЗ_L, None),
    ("F11", "MiniMax Token Plan $22 / $55 / $132 (A3)",
     r"\$22", ("H", "N"), None),
    ("F12", "Ревизия G22 для Astra (Б3)",
     r"НЕ переносится|не переносится", ВСЕ, None),
    ("F13", "Grok 4.7 — не пре-маршрутизировать",
     r"4\.7", БЕЗ_L, None),
    ("F14", "Алиасов -latest в телах нет",
     None, (), r"-latest"),
]


def прогон(корень, поток=sys.stdout):
    список, версия = тела(корень)
    if len(список) != 5:
        поток.write("ПРОВАЛ: тел поставки %d при ожидаемых 5 (корень %s)\n" % (len(список), корень))
        return 2
    свод = собрать(список)
    всего = sum(len(v) for v in свод.values())
    поток.write("ПРИЁМКА ФАКТОВ live specs (срез 8.7.4)  поколение %s · корень %s\n" % (версия, корень))
    поток.write("  тела: %s\n" % " · ".join("%s %d" % (к, len(свод[к])) for к, _ in список))
    if всего == 0:
        поток.write("ПРОВАЛ: осмотрено 0 объектов — заслон не на что натравить\n")
        return 2

    провалов = 0
    осмотрено_всего = 0
    for правило in ФАКТЫ:
        код, имя, есть, где, нет_ли = правило[:5]
        исключение = правило[5] if len(правило) > 5 else None
        беды = []
        осмотрено = 0
        for ключ in (где or ВСЕ):
            for путь, текст in свод.get(ключ, []):
                осмотрено += 1
        # (а) факт обязан быть назван в каждом теле из списка
        if есть:
            для_вывода = []
            for ключ in где:
                попаданий = sum(1 for _, т in свод.get(ключ, []) if re.search(есть, т))
                для_вывода.append("%s %d" % (ключ, попаданий))
                if попаданий == 0:
                    беды.append("тело %s не называет факт" % ключ)
            подпись = " · ".join(для_вывода)
        else:
            подпись = "проверка только на отсутствие"
        # (б) отменённое значение не должно остаться НИГДЕ, кроме файлов истории
        if нет_ли:
            for ключ in ВСЕ:
                for путь, текст in свод.get(ключ, []):
                    if any(h in os.path.basename(путь).upper() for h in ИСТОРИЯ):
                        continue
                    for строка in текст.split("\n"):
                        if исключение and re.search(исключение, строка):
                            continue
                        if re.search(нет_ли, строка):
                            беды.append("%s: осталось отменённое — %s" % (
                                os.path.relpath(путь, корень), строка.strip()[:90]))
        осмотрено_всего += осмотрено
        провалов += len(беды)
        поток.write("  %-4s %-46s %s  осмотрено %4d · провалов %d\n"
                    % (код, имя, "ок    " if not беды else "ПРОВАЛ", осмотрено, len(беды)))
        if подпись != "проверка только на отсутствие":
            поток.write("          по телам: %s\n" % подпись)
        for б in беды[:6]:
            поток.write("          ✗ %s\n" % б)
        if len(беды) > 6:
            поток.write("          … ещё %d\n" % (len(беды) - 6))

    поток.write("\n  ИТОГО осмотрено объектов %d при ожидаемых %d · провалов %d\n"
                % (осмотрено_всего, осмотрено_всего, провалов))
    if провалов:
        поток.write("ФАКТЫ РАЗОШЛИСЬ С ЭТАЛОНОМ — код 2\n")
        return 2
    поток.write("ФАКТЫ НА МЕСТЕ ВО ВСЕХ ТЕЛАХ — код 0\n")
    return 0


def пара(поток=sys.stdout):
    """Парный прогон: здоровое дерево проходит, дерево с возвращённым старым значением падает."""
    поток.write("=" * 78 + "\nПОЛОВИНА 1 — нужное проходит (рабочее дерево)\n" + "=" * 78 + "\n")
    здоровый = прогон(ROOT, поток)

    поток.write("\n" + "=" * 78 + "\nПОЛОВИНА 2 — запрещённое падает (копия с возвращённым старым)\n"
                + "=" * 78 + "\n")
    with tempfile.TemporaryDirectory(prefix="факты-мутация-") as tmp:
        список, версия = тела(ROOT)
        for _, путь in список:
            отн = os.path.relpath(путь, ROOT)
            shutil.copytree(путь, os.path.join(tmp, отн))
        мутации = [
            ("$3/$15 у Sonnet 5 вернулся в таблицу C",
             os.path.join(tmp, "editions", "%s-C" % версия, "for-chat", "_live", "live_claude.md"),
             "$2 / $10 (подорожание до $3/$15 с 01.09 ОТМЕНЕНО 10.08)",
             "$2 (intro) → $3 c 01.09"),
            ("«xAI» вернулся в таблицу порогов C",
             os.path.join(tmp, "editions", "%s-C" % версия, "for-chat", "_live", "live_vendors.md"),
             "| SpaceXAI (grok-4.5) |",
             "| xAI (grok-4.5) |"),
            ("старый счётчик пропусков GA вернулся в H",
             os.path.join(tmp, "editions", "%s-H" % версия, "files", "_live", "live_core.md"),
             "PREVIEW — ПЯТЫЙ пропуск GA",
             "PREVIEW — ТРЕТИЙ пропуск GA"),
        ]
        внесено = 0
        for имя, путь, было, стало in мутации:
            if not os.path.isfile(путь):
                поток.write("  мутация «%s» НЕ ВНЕСЕНА: нет файла %s\n" % (имя, путь))
                continue
            т = io.open(путь, encoding="utf-8").read()
            if т.count(было) != 1:
                поток.write("  мутация «%s» НЕ ВНЕСЕНА: якорь встречается %d раз\n"
                            % (имя, т.count(было)))
                continue
            io.open(путь, "w", encoding="utf-8", newline="\n").write(т.replace(было, стало, 1))
            поток.write("  внесена мутация: %s\n" % имя)
            внесено += 1
        поток.write("  мутаций внесено %d при ожидаемых %d\n\n" % (внесено, len(мутации)))
        больной = прогон(tmp, поток)

    поток.write("\n" + "=" * 78 + "\n")
    поток.write("  нужное проходит: %s (код %d, ожидался 0)\n"
                % ("да" if здоровый == 0 else "НЕТ", здоровый))
    поток.write("  запрещённое падает: %s (код %d, ожидался 2)\n"
                % ("да" if больной == 2 else "НЕТ — ПРОВЕРКА МЕРТВА", больной))
    итог = 0 if (здоровый == 0 and больной == 2) else 2
    поток.write("  ПАРА: %s\n" % ("сошлась, код 0" if итог == 0 else "НЕ СОШЛАСЬ, код 2"))
    return итог


if __name__ == "__main__":
    if "--пара" in sys.argv:
        sys.exit(пара())
    корень = ROOT
    if "--корень" in sys.argv:
        корень = sys.argv[sys.argv.index("--корень") + 1]
    sys.exit(прогон(корень))
